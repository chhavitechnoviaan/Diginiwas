import express from "express";
import {createPromotionRequest,getPromotionRequests,getMyPromotionRequests,approvePromotionRequest,rejectPromotionRequest,expirePromotions} from "../../controllers/Promotion/promotionV2Controller.js";
import {protect,requireAdmin} from "../../middleware/authMiddleware.js";
import {createSellerBoostRequest,listSellerBoostRequests,getSellerBoostRequest,approveSellerBoostRequest,rejectSellerBoostRequest} from "../../controllers/Promotion/sellerBoostController.js";
import {activeProperties,activePartners} from "../../controllers/Promotion/activePromotionController.js";
const router=express.Router();
router.get("/active/properties",activeProperties);
router.get("/active/partners",activePartners);
router.post("/seller-request",protect,createSellerBoostRequest);
router.get("/seller-requests",protect,listSellerBoostRequests);
router.get("/partner-requests",protect,listSellerBoostRequests);
router.get("/seller-request/:id",protect,getSellerBoostRequest);
router.patch("/seller-request/:id/approve",protect,approveSellerBoostRequest);
router.patch("/seller-request/:id/reject",protect,rejectSellerBoostRequest);
router.post("/",protect,createPromotionRequest);
router.post("/partner/request",protect,(req,_res,next)=>{req.body.targetType="PARTNER";next()},createPromotionRequest);
router.post("/property/request",protect,(req,_res,next)=>{req.body.targetType="PROPERTY";next()},createPromotionRequest);
router.get("/my",protect,getMyPromotionRequests);
router.get("/",protect,requireAdmin,getPromotionRequests);
router.post("/maintenance/expire",protect,requireAdmin,expirePromotions);
router.patch("/:id/approve",protect,requireAdmin,approvePromotionRequest);
router.patch("/:id/reject",protect,requireAdmin,rejectPromotionRequest);
export default router;
